-- Roles, warehouse, cost guard, database, and schema. Run as ACCOUNTADMIN
-- (scripts/lq.py setup). Requires session variable lq_db.

SET lq_me = '"' || CURRENT_USER() || '"';  -- quoted: user names can be case-sensitive

CREATE ROLE IF NOT EXISTS LQ_OWNER COMMENT = 'Owns Local Quest catalog objects and procedures';
CREATE ROLE IF NOT EXISTS LQ_APP_RO COMMENT = 'Backend service role: may only call APP.GET_CANDIDATES';
GRANT ROLE LQ_OWNER TO ROLE SYSADMIN;
GRANT ROLE LQ_APP_RO TO ROLE LQ_OWNER;
GRANT ROLE LQ_OWNER TO USER IDENTIFIER($lq_me);

CREATE WAREHOUSE IF NOT EXISTS LQ_WH
    WAREHOUSE_SIZE = XSMALL
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;
GRANT USAGE, OPERATE ON WAREHOUSE LQ_WH TO ROLE LQ_OWNER;
GRANT USAGE ON WAREHOUSE LQ_WH TO ROLE LQ_APP_RO;

-- Cost guard. The quota is a proposal; confirm it with the team budget.
CREATE RESOURCE MONITOR IF NOT EXISTS LQ_MONITOR
    WITH CREDIT_QUOTA = 10
    FREQUENCY = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS ON 80 PERCENT DO NOTIFY
             ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE LQ_WH SET RESOURCE_MONITOR = LQ_MONITOR;

-- Cortex embedding functions.
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE LQ_OWNER;

GRANT CREATE DATABASE ON ACCOUNT TO ROLE LQ_OWNER;
USE ROLE LQ_OWNER;
CREATE DATABASE IF NOT EXISTS IDENTIFIER($lq_db);
USE DATABASE IDENTIFIER($lq_db);
CREATE SCHEMA IF NOT EXISTS QUEST;
